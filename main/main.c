static float fp16_to_float(uint16_t h)
{
    uint32_t sign = (h >> 15) & 0x1u;
    uint32_t exp  = (h >> 10) & 0x1Fu;
    uint32_t mant = h & 0x3FFu;
    float    v;
    if (exp == 0) {
        v = ldexpf((float)mant, -24);
    } else if (exp == 31) {
        v = mant ? NAN : INFINITY;
    } else {
        v = ldexpf((float)(mant | 0x400u), (int)exp - 25);
    }
    return sign ? -v : v;
}

static void sflp_to_quat(const uint8_t data[6], float q[4])
{
    q[0] = fp16_to_float((uint16_t)(data[0] | (data[1] << 8)));
    q[1] = fp16_to_float((uint16_t)(data[2] | (data[3] << 8)));
    q[2] = fp16_to_float((uint16_t)(data[4] | (data[5] << 8)));
    float sumsq = q[0] * q[0] + q[1] * q[1] + q[2] * q[2];
    if (sumsq > 1.0f) {
        float n = sqrtf(sumsq);
        q[0] /= n; q[1] /= n; q[2] /= n;
        sumsq = 1.0f;
    }
    q[3] = sqrtf(1.0f - sumsq);
}

static bool sflp_init(imu_unit_t *u)
{
    lsm6dsv16x_fifo_sflp_raw_t batch = { 0 };
    lsm6dsv16x_sflp_gbias_t    gbias = { 0 };
    int32_t rc = 0;
    rc |= lsm6dsv16x_fifo_mode_set(&u->ctx, LSM6DSV16X_BYPASS_MODE);
    batch.game_rotation = PROPERTY_ENABLE;
    batch.gravity       = PROPERTY_ENABLE;
    rc |= lsm6dsv16x_fifo_sflp_batch_set(&u->ctx, batch);
    rc |= lsm6dsv16x_sflp_data_rate_set(&u->ctx, LSM6DSV16X_SFLP_60Hz);
    rc |= lsm6dsv16x_sflp_game_gbias_set(&u->ctx, &gbias);
    rc |= lsm6dsv16x_sflp_game_rotation_set(&u->ctx, PROPERTY_ENABLE);
    rc |= lsm6dsv16x_fifo_watermark_set(&u->ctx, 8);
    rc |= lsm6dsv16x_fifo_mode_set(&u->ctx, LSM6DSV16X_STREAM_MODE);
    return rc == 0;
}

static void drain_fifo(imu_unit_t *u, float q[4], bool *have_q)
{
    lsm6dsv16x_fifo_status_t st = { 0 };
    if (lsm6dsv16x_fifo_status_get(&u->ctx, &st) != 0) {
        return;
    }
    for (int guard = 0; guard < 64 && st.fifo_level; guard++) {
        lsm6dsv16x_fifo_out_raw_t e = { 0 };
        if (lsm6dsv16x_fifo_out_raw_get(&u->ctx, &e) != 0) {
            return;
        }
        if (e.tag == LSM6DSV16X_SFLP_GAME_ROTATION_VECTOR_TAG) {
            sflp_to_quat(e.data, q);
            *have_q = true;
        }
        if (lsm6dsv16x_fifo_status_get(&u->ctx, &st) != 0) {
            return;
        }
    }
}

static bool stream_init_unit(imu_unit_t *u)
{
    if (!identity_probe(u)) {
        return false;
    }
    test_ctx_t t = { 0 };
    if (!unit_configure(u, &t, false)) {
        return false;
    }
    u->sflp_ok = sflp_init(u);
    if (!u->sflp_ok) {
        ESP_LOGW(TAG, "unit %d: SFLP unavailable, raw only", (int)(u - s_units));
    }
    u->present = true;
    u->misses  = 0;
    return true;
}

/* Re-check identity so a source that is unplugged stops being reported and a
 * newly plugged source is picked up. Returns true if the state changed. */
static bool hotplug_step(int index)
{
    imu_unit_t *u = &s_units[index];
    bool id_ok = identity_probe(u);
    bool changed = false;

    if (u->present && !id_ok) {
        if (++u->misses >= MISS_LIMIT) {
            u->present = false;
            u->misses  = 0;
            u->sflp_ok = false;
            printf("HOTPLUG %d REMOVED\n", index);
            fflush(stdout);
            changed = true;
        }
    } else if (!u->present && id_ok) {
        if (stream_init_unit(u)) {
            printf("HOTPLUG %d ADDED id=0x%02X\n", index, u->who_am_i);
            fflush(stdout);
            changed = true;
        }
    } else {
        u->misses = 0;
    }
    return changed;
}

static void run_stream(void)
{
    for (int i = 0; i < CONFIG_UNIT_COUNT; i++) {
        unit_bind(&s_units[i], i);
        stream_init_unit(&s_units[i]);
    }

    int live = 0;
    for (int i = 0; i < CONFIG_UNIT_COUNT; i++) {
        live += s_units[i].present ? 1 : 0;
    }
    printf("STREAM_READY %d\n", live);
    fflush(stdout);

    const int period_ms = 1000 / CONFIG_STREAM_HZ;
    int64_t next = esp_timer_get_time();
    int64_t next_hotplug = esp_timer_get_time() + HOTPLUG_PERIOD_US;
    int     hotplug_cursor = 0;

    while (true) {
        /* One write per frame. Writing each source separately pushed the
         * USB-Serial/JTAG link down to ~7 frames/s with 11 slots, because
         * every printf became its own USB transfer. */
        static char buf[4096];
        int off = snprintf(buf, sizeof(buf), "{\"t\":%lld,\"u\":[",
                           (long long)(esp_timer_get_time() / 1000));
        bool first = true;
        for (int i = 0; i < CONFIG_UNIT_COUNT; i++) {
            imu_unit_t *u = &s_units[i];
            if (off < 0 || (size_t)off > sizeof(buf) - 256) {
                break; /* cannot happen with 11 sources; keep the write safe */
            }

            float acc[3] = { 0 }, gyro[3] = { 0 };
            bool  have_acc = false, have_gyro = false;
            float q[4] = { 0, 0, 0, 1 };
            bool  have_q = false;

            if (u->present) {
                read_sample(u, acc, gyro, &have_acc, &have_gyro);
                if (u->sflp_ok) {
                    drain_fifo(u, q, &have_q);
                }
            }

            if (!u->present) {
                off += snprintf(buf + off, sizeof(buf) - off,
                                "%s{\"i\":%d,\"on\":0,\"cs\":%d}",
                                first ? "" : ",", i, u->cs);
                first = false;
                continue;
            }

            off += snprintf(buf + off, sizeof(buf) - off,
                   "%s{\"i\":%d,\"on\":1,\"id\":%d,\"cs\":%d,\"e\":%u,"
                   "\"na\":%u,\"ng\":%u,"
                   "\"a\":[%.3f,%.3f,%.3f],\"g\":[%.3f,%.3f,%.3f],"
                   "\"q\":[%.4f,%.4f,%.4f,%.4f],\"aq\":%d,\"va\":%d,\"vg\":%d}",
                   first ? "" : ",", i, u->who_am_i, u->cs,
                   (unsigned)u->errors, (unsigned)u->samples_a,
                   (unsigned)u->samples_g,
                   acc[0], acc[1], acc[2], gyro[0], gyro[1], gyro[2],
                   q[0], q[1], q[2], q[3],
                   have_q ? 1 : 0, have_acc ? 1 : 0, have_gyro ? 1 : 0);
            first = false;
        }
        if (off < 0) {
            off = 0;
        }
        if ((size_t)off > sizeof(buf) - 3) {
            off = sizeof(buf) - 3;
        }
        off += snprintf(buf + off, sizeof(buf) - off, "]}\n");
        fwrite(buf, 1, (size_t)off, stdout);
        fflush(stdout);

        /* Probe one source per second (round-robin) rather than all at once,
         * so a probe never adds a visible burst to the stream. */
        int64_t now = esp_timer_get_time();
        if (now >= next_hotplug) {
            hotplug_step(hotplug_cursor);
            hotplug_cursor = (hotplug_cursor + 1) % CONFIG_UNIT_COUNT;
            next_hotplug = now + HOTPLUG_PERIOD_US;
        }

        next += (int64_t)period_ms * 1000;
        now = esp_timer_get_time();
        if (next > now) {
            vTaskDelay(pdMS_TO_TICKS((next - now) / 1000));
        } else {
            next = now;
        }
    }
}

