/* ------------------------------------------------------------------ config */

#define IMU_PIN_SCLK  GPIO_NUM_12
#define IMU_PIN_MOSI  GPIO_NUM_11
#define IMU_PIN_MISO  GPIO_NUM_13

#define MAX_UNITS     11
#define IMU_SPI_HOST  SPI2_HOST
#define IMU_SPI_HZ    (CONFIG_IMU_SPI_KHZ * 1000)

/* Physical sanity limits for a board sitting still on a desk. */
#define ACC_MAG_MIN_G     0.85f
#define ACC_MAG_MAX_G     1.15f
#define GYRO_BIAS_MAX_DPS 3.0f
#define GYRO_NOISE_MAX_DPS 1.0f

/* A source is declared gone only after this many consecutive identity misses,
 * so one corrupt frame does not flap the UI. */
#define MISS_LIMIT 3
#define HOTPLUG_PERIOD_US 1000000

/* The pin table is the one vetted in the cleanroom project: it avoids the USB
 * pins (19/20), the S3 strapping pins (0/3/45/46) and the N16R8 flash/PSRAM
 * pins. */
static const int k_cs_pins[MAX_UNITS] = {
    CONFIG_IMU_CS_GPIO_0, CONFIG_IMU_CS_GPIO_1, CONFIG_IMU_CS_GPIO_2,
    CONFIG_IMU_CS_GPIO_3, CONFIG_IMU_CS_GPIO_4, CONFIG_IMU_CS_GPIO_5,
    CONFIG_IMU_CS_GPIO_6, CONFIG_IMU_CS_GPIO_7, CONFIG_IMU_CS_GPIO_8,
    CONFIG_IMU_CS_GPIO_9, CONFIG_IMU_CS_GPIO_10,
};

/* ------------------------------------------------------------------- state */

typedef struct {
    int              cs;
    stmdev_ctx_t     ctx;
    bool             present;
    uint8_t          who_am_i;
    uint8_t          misses;
    uint32_t         errors;
    uint32_t         samples_a;
    uint32_t         samples_g;
    bool             sflp_ok;
} imu_unit_t;

static imu_unit_t s_units[MAX_UNITS];
static spi_device_handle_t s_bus_dev;
static int s_routed_cs = -1;
static uint32_t s_st_hist[256];
static int s_block_dump;

/* ------------------------------------------------------- SPI transport ---- */

/* Return a pin to the plain GPIO output driver and force it high. Until this
 * is done the pin is still fed by the SPI CS0 signal and would follow the
 * next transaction's chip select. */
static void cs_release(int cs)
{
    esp_rom_gpio_connect_out_signal(cs, SIG_GPIO_OUT_IDX, false, false);
    gpio_set_level(cs, 1);
}

static void cs_select(int cs)
{
    if (s_routed_cs == cs) {
        return;
    }
    if (s_routed_cs >= 0) {
        cs_release(s_routed_cs);
    }
    esp_rom_gpio_connect_out_signal(cs, spi_periph_signal[IMU_SPI_HOST].spics_out[0],
                                    false, false);
    s_routed_cs = cs;
}

static int32_t unit_transfer(imu_unit_t *u, uint8_t reg, const uint8_t *in,
                             uint8_t *out, uint16_t n)
{
    if (n == 0 || n > 32) {
        return ESP_ERR_INVALID_ARG;
    }

    uint8_t tx[33] = { reg };
    uint8_t rx[33] = { 0 };
    if (in) {
        memcpy(&tx[1], in, n);
    }

    spi_transaction_t t = {
        .length    = (size_t)(n + 1) * 8,
        .rxlength  = out ? (size_t)(n + 1) * 8 : 0,
        .tx_buffer = tx,
        .rx_buffer = out ? rx : NULL,
    };

    /* One owner: the whole select -> frame -> deselect window is held under
     * the bus lock so a second task (the hot-plug probe) cannot reroute CS
     * between the address byte and the payload. */
    int rc = spi_device_acquire_bus(s_bus_dev, portMAX_DELAY);
    if (rc != 0) {
        return rc;
    }
    cs_select(u->cs);
    rc = spi_device_polling_transmit(s_bus_dev, &t);
    /* Leave CS0 routed. Detaching the matrix after every transaction adds a
     * glitch at the next frame's start: the peripheral asserts CS before the
     * reroute settles, the device never decodes the command, and MISO reads
     * 0xFF followed by zeros. The previous source is released only when the
     * next transaction selects a different pin (cs_select). */
    spi_device_release_bus(s_bus_dev);

    if (rc == 0 && out) {
        memcpy(out, &rx[1], n);
    }
    return rc;
}

static int32_t rd(void *h, uint8_t reg, uint8_t *buf, uint16_t len)
{
    return unit_transfer((imu_unit_t *)h, (uint8_t)(reg | 0x80), NULL, buf, len);
}

static int32_t wr(void *h, uint8_t reg, const uint8_t *buf, uint16_t len)
{
    return unit_transfer((imu_unit_t *)h, (uint8_t)(reg & 0x7F), buf, NULL, len);
}

static void mdelay(uint32_t ms)
{
    vTaskDelay(pdMS_TO_TICKS(ms ? ms : 1));
}

/* ------------------------------------------------------------- test log --- */

typedef struct {
    int  passed;
    int  failed;
    char detail[192];
} test_ctx_t;

static void check(test_ctx_t *t, bool ok, const char *fmt, ...)
{
    if (ok) {
        t->passed++;
    } else {
        t->failed++;
    }
    if (!ok && t->detail[0] == '\0') {
        va_list ap;
        va_start(ap, fmt);
        vsnprintf(t->detail, sizeof(t->detail), fmt, ap);
        va_end(ap);
    }
}

static int unit_total(const test_ctx_t *t) { return t->passed + t->failed; }

/* ------------------------------------------------------------ unit setup -- */

static void unit_bind(imu_unit_t *u, int index)
{
    memset(u, 0, sizeof(*u));
    u->cs = k_cs_pins[index];
    u->ctx.write_reg = wr;
    u->ctx.read_reg  = rd;
    u->ctx.mdelay    = mdelay;
    u->ctx.handle    = u;
}

static esp_err_t bus_init(void)
{
    for (int i = 0; i < CONFIG_UNIT_COUNT; i++) {
        int cs = k_cs_pins[i];
        if (cs == 19 || cs == 20) {
            ESP_LOGE(TAG, "CS GPIO%d is a USB pin; refusing to drive it", cs);
            return ESP_ERR_INVALID_ARG;
        }
        for (int j = 0; j < i; j++) {
            if (k_cs_pins[j] == cs) {
                ESP_LOGE(TAG, "duplicate CS GPIO%d in unit table", cs);
                return ESP_ERR_INVALID_ARG;
            }
        }
        gpio_config_t c = {
            .pin_bit_mask = 1ULL << cs,
            .mode         = GPIO_MODE_OUTPUT,
            .pull_up_en   = GPIO_PULLUP_DISABLE,
            .pull_down_en = GPIO_PULLDOWN_DISABLE,
            .intr_type    = GPIO_INTR_DISABLE,
        };
        ESP_ERROR_CHECK(gpio_config(&c));
        cs_release(cs); /* idle high before the bus is enabled */
    }

    spi_bus_config_t bus = {
        .miso_io_num     = IMU_PIN_MISO,
        .mosi_io_num     = IMU_PIN_MOSI,
        .sclk_io_num     = IMU_PIN_SCLK,
        .quadwp_io_num   = -1,
        .quadhd_io_num   = -1,
        .max_transfer_sz = 64,
    };
    esp_err_t err = spi_bus_initialize(IMU_SPI_HOST, &bus, SPI_DMA_DISABLED);
    if (err != ESP_OK) {
        return err;
    }

    /* The device occupies hardware CS0 (pin 0 is only the slot anchor; the
     * signal is rerouted per transaction). */
    spi_device_interface_config_t dev = {
        .clock_speed_hz   = IMU_SPI_HZ,
        .mode             = 3,
        .spics_io_num     = k_cs_pins[0],
        .cs_ena_pretrans  = 1,
        .cs_ena_posttrans = 1,
        .queue_size       = 1,
        .flags            = 0, /* full duplex */
    };
    return spi_bus_add_device(IMU_SPI_HOST, &dev, &s_bus_dev);
}

/* ------------------------------------------------------------- identify --- */

static bool identity_probe(imu_unit_t *u)
{
    uint8_t id = 0;
    int32_t rc = lsm6dsv16x_device_id_get(&u->ctx, &id);
    u->who_am_i = id;
    return rc == 0 && id == LSM6DSV16X_ID;
}

/* Configure one present source. Every step's return code and the raw readback
 * are checked; the driver's own returns are not a substitute for readback. */
static bool unit_configure(imu_unit_t *u, test_ctx_t *t, bool verbose)
{
    int32_t rc;
    bool ok = true;

#define STEP(expr, what)                                            \
    do {                                                            \
        rc = (expr);                                                \
        if (verbose) check(t, rc == 0, what " rc=%ld", (long)rc);   \
        ok = ok && (rc == 0);                                       \
    } while (0)

    STEP(lsm6dsv16x_sw_por(&u->ctx), "sw_por");
    if (!ok) {
        return false;
    }
    vTaskDelay(pdMS_TO_TICKS(20));

#ifdef CONFIG_USE_BDU
    STEP(lsm6dsv16x_block_data_update_set(&u->ctx, PROPERTY_ENABLE), "bdu");
#else
    STEP(lsm6dsv16x_block_data_update_set(&u->ctx, PROPERTY_DISABLE), "bdu off");
#endif
    STEP(lsm6dsv16x_xl_full_scale_set(&u->ctx, LSM6DSV16X_2g), "xl fs");
    STEP(lsm6dsv16x_gy_full_scale_set(&u->ctx, LSM6DSV16X_2000dps), "gy fs");
    STEP(lsm6dsv16x_xl_mode_set(&u->ctx, LSM6DSV16X_XL_HIGH_PERFORMANCE_MD), "xl mode");
    STEP(lsm6dsv16x_gy_mode_set(&u->ctx, LSM6DSV16X_GY_HIGH_PERFORMANCE_MD), "gy mode");
    STEP(lsm6dsv16x_xl_data_rate_set(&u->ctx, LSM6DSV16X_ODR_AT_120Hz), "xl odr");
    STEP(lsm6dsv16x_gy_data_rate_set(&u->ctx, LSM6DSV16X_ODR_AT_120Hz), "gy odr");
#undef STEP

    uint8_t ctrl1 = 0, ctrl2 = 0, ctrl3 = 0, ctrl6 = 0, ctrl8 = 0, st = 0;
    lsm6dsv16x_read_reg(&u->ctx, LSM6DSV16X_CTRL1, &ctrl1, 1);
    lsm6dsv16x_read_reg(&u->ctx, LSM6DSV16X_CTRL2, &ctrl2, 1);
    lsm6dsv16x_read_reg(&u->ctx, LSM6DSV16X_CTRL3, &ctrl3, 1);
    lsm6dsv16x_read_reg(&u->ctx, LSM6DSV16X_CTRL6, &ctrl6, 1);
    lsm6dsv16x_read_reg(&u->ctx, LSM6DSV16X_CTRL8, &ctrl8, 1);
    lsm6dsv16x_read_reg(&u->ctx, LSM6DSV16X_STATUS_REG, &st, 1);
    ESP_LOGI(TAG, "  unit %d: CTRL1=0x%02X CTRL2=0x%02X CTRL3=0x%02X "
                  "CTRL6=0x%02X CTRL8=0x%02X STATUS=0x%02X",
             (int)(u - s_units), ctrl1, ctrl2, ctrl3, ctrl6, ctrl8, st);
    if (verbose) {
        check(t, ctrl1 == 0x06, "CTRL1 readback 0x%02X (want 0x06)", ctrl1);
        check(t, ctrl2 == 0x06, "CTRL2 readback 0x%02X (want 0x06)", ctrl2);
        check(t, (ctrl3 & 0x04) != 0, "CTRL3 IF_INC clear (0x%02X)", ctrl3);
        check(t, (ctrl6 & 0x0F) == 0x04, "CTRL6 FS_G=%u (want 4=2000dps)",
              ctrl6 & 0x0F);
    }
    ok = ok && ctrl1 == 0x06 && ctrl2 == 0x06;
    return ok;
}

/* ------------------------------------------------------------ sampling ---- */

static bool read_sample(imu_unit_t *u, float acc_g[3], float gyro_dps[3],
                        bool *have_acc, bool *have_gyro)
{
    /* Read STATUS as a raw byte: the bit-field view is fine for control but
     * hides which exact flag was set when a frame looks corrupt. */
    uint8_t st = 0;
    if (lsm6dsv16x_read_reg(&u->ctx, LSM6DSV16X_STATUS_REG, &st, 1) != 0) {
        return false;
    }
    s_st_hist[st]++;
    bool drdy_xl = (st & 0x01) != 0;
    bool drdy_gy = (st & 0x02) != 0;
    if (!drdy_xl && !drdy_gy) {
        return false;
    }

    int16_t ar[3] = { 0 }, gr[3] = { 0 };
    if (drdy_xl || drdy_gy) {
        /* Gyro (0x22..0x27) and accel (0x28..0x2D) are one contiguous block.
         * Reading it in a single transaction replaces two back-to-back bursts
         * and gives a coherent snapshot under BDU.
         *
         * A breadboard bus can drop the frame after the first byte; that shows
         * up as an all-zero block, never as plausible sensor data (a live
         * accelerometer always reports roughly 1 g). Retry the block instead
         * of feeding the zeros into the statistics. */
        bool valid = false;
        for (int attempt = 0; attempt < 5 && !valid; attempt++) {
            uint8_t buf[12];
#ifdef CONFIG_READ_BYTE_WISE
            const int chunk = 1;
#else
            const int chunk = CONFIG_BURST_LEN;
#endif
            int rc = 0;
            for (int off = 0; off < 12; off += chunk) {
                int n = 12 - off;
                if (n > chunk) {
                    n = chunk;
                }
                rc |= lsm6dsv16x_read_reg(&u->ctx,
                                          (uint8_t)(LSM6DSV16X_OUTX_L_G + off),
                                          &buf[off], (uint16_t)n);
            }
            if (rc != 0) {
                u->errors++;
                continue;
            }
#ifdef CONFIG_DUMP_BLOCK
            if (s_block_dump > 0) {
                s_block_dump--;
                printf("BLOCK %d", (int)(u - s_units));
                for (int k = 0; k < 12; k++) {
                    printf(" %02X", buf[k]);
                }
                printf("\n");
            }
#endif
            for (int i = 0; i < 3; i++) {
                gr[i] = (int16_t)(((uint16_t)buf[2 * i + 1] << 8) | buf[2 * i]);
                ar[i] = (int16_t)(((uint16_t)buf[6 + 2 * i + 1] << 8) | buf[6 + 2 * i]);
            }
            /* A truncated frame shows the first byte and zeros after it. The
             * accelerometer makes that detectable: at rest the vector is
             * ~1 g, so an implausible magnitude means the frame did not
             * arrive intact. 1 g is 16384 LSB at the 2 g range; accept
             * 0.2..3 g and retry anything outside. */
            int64_t a2 = (int64_t)ar[0] * ar[0] + (int64_t)ar[1] * ar[1] +
                         (int64_t)ar[2] * ar[2];
            valid = a2 > 3300LL * 3300 && a2 < 49000LL * 49000;
            if (!valid) {
                u->errors++;
            }
        }
        if (!valid) {
            return false;
        }
    }
    if (drdy_xl) {
        for (int i = 0; i < 3; i++) {
            acc_g[i] = lsm6dsv16x_from_fs2_to_mg(ar[i]) / 1000.0f;
        }
        *have_acc = true;
        u->samples_a++;
    }
    if (drdy_gy) {
        for (int i = 0; i < 3; i++) {
            gyro_dps[i] = lsm6dsv16x_from_fs2000_to_mdps(gr[i]) / 1000.0f;
        }
        *have_gyro = true;
        u->samples_g++;
    }

#ifdef CONFIG_DUMP_RAW
    printf("SAMPLE %d %lld %02X %d %d %d %d %d %d %.3f %.3f %.3f %.3f %.3f %.3f\n",
           (int)(u - s_units), (long long)esp_timer_get_time(), st,
           ar[0], ar[1], ar[2], gr[0], gr[1], gr[2],
           acc_g[0], acc_g[1], acc_g[2], gyro_dps[0], gyro_dps[1], gyro_dps[2]);
#endif
    return true;
}

static void test_data_path(imu_unit_t *u, test_ctx_t *t)
{
    float acc[3] = { 0 }, gyro[3] = { 0 };
    bool  have_acc = false, have_gyro = false;

    for (int i = 0; i < 40 && !(have_acc && have_gyro); i++) {
        read_sample(u, acc, gyro, &have_acc, &have_gyro);
        vTaskDelay(pdMS_TO_TICKS(10));
    }

    check(t, have_acc, "no accelerometer sample");
    check(t, have_gyro, "no gyroscope sample");
    if (!have_acc) {
        return;
    }
    float mag = sqrtf(acc[0] * acc[0] + acc[1] * acc[1] + acc[2] * acc[2]);
    check(t, mag >= 0.5f && mag <= 2.5f, "acc magnitude %.3f g implausible", mag);

    int zero_axes = 0;
    for (int i = 0; i < 3; i++) {
        if (fabsf(acc[i]) < 0.001f) {
            zero_axes++;
        }
    }
    check(t, zero_axes < 2, "%d accel axes exactly zero", zero_axes);
}

static void test_static_window(imu_unit_t *u, test_ctx_t *t)
{
    const int64_t window_us = 1000000;
    int64_t start = esp_timer_get_time();
    double ax = 0, ay = 0, az = 0, gx = 0, gy = 0, gz = 0;
    double gx2 = 0, gy2 = 0, gz2 = 0;
    float  gx_min = 1e9f, gx_max = -1e9f;
    int got_acc = 0, got_gyro = 0;

    memset(s_st_hist, 0, sizeof(s_st_hist));
    s_block_dump = 12;
    while (esp_timer_get_time() - start < window_us) {
        float acc[3] = { 0 }, gyro[3] = { 0 };
        bool have_acc = false, have_gyro = false;
        if (read_sample(u, acc, gyro, &have_acc, &have_gyro)) {
            if (have_acc) {
                ax += acc[0]; ay += acc[1]; az += acc[2]; got_acc++;
            }
            if (have_gyro) {
                gx += gyro[0]; gy += gyro[1]; gz += gyro[2];
                gx2 += (double)gyro[0] * gyro[0];
                gy2 += (double)gyro[1] * gyro[1];
                gz2 += (double)gyro[2] * gyro[2];
                if (gyro[0] < gx_min) gx_min = gyro[0];
                if (gyro[0] > gx_max) gx_max = gyro[0];
                got_gyro++;
            }
        }
        vTaskDelay(pdMS_TO_TICKS(1));
    }

    int64_t elapsed_us = esp_timer_get_time() - start;
    int expected = (int)((elapsed_us * 120) / 1000000);
    ESP_LOGI(TAG, "  unit %d window %.2fs acc=%d gyro=%d expected~%d "
                  "gx[min=%.2f max=%.2f] spi=%dkHz",
             (int)(u - s_units), (double)elapsed_us / 1e6, got_acc, got_gyro,
             expected, got_gyro ? gx_min : 0.0f, got_gyro ? gx_max : 0.0f,
             CONFIG_IMU_SPI_KHZ);

    char hist[160];
    int  ho = 0;
    for (int v = 0; v < 256 && ho < (int)sizeof(hist) - 12; v++) {
        if (s_st_hist[v]) {
            ho += snprintf(hist + ho, sizeof(hist) - ho, "%02X:%u ", v,
                           (unsigned)s_st_hist[v]);
        }
    }
    ESP_LOGI(TAG, "  unit %d status hist: %s", (int)(u - s_units),
             ho ? hist : "(none)");

    check(t, got_acc >= expected * 4 / 5, "only %d accel samples (~%d)", got_acc,
          expected);
    check(t, got_gyro >= expected * 4 / 5, "only %d gyro samples (~%d)",
          got_gyro, expected);
    if (got_acc < expected * 4 / 5 || got_gyro < expected * 4 / 5) {
        return;
    }

    double mag = sqrt((ax / got_acc) * (ax / got_acc) +
                      (ay / got_acc) * (ay / got_acc) +
                      (az / got_acc) * (az / got_acc));
    check(t, mag >= ACC_MAG_MIN_G && mag <= ACC_MAG_MAX_G, "mean |a|=%.3f g",
          mag);

    const double b[3] = { gx / got_gyro, gy / got_gyro, gz / got_gyro };
    const double q[3] = { gx2 / got_gyro, gy2 / got_gyro, gz2 / got_gyro };
    ESP_LOGI(TAG, "  unit %d gyro bias %.2f %.2f %.2f dps",
             (int)(u - s_units), b[0], b[1], b[2]);
    const char *name[3] = { "x", "y", "z" };
    for (int i = 0; i < 3; i++) {
        double var = q[i] - b[i] * b[i];
        double noise = sqrt(var > 0 ? var : 0);
        check(t, fabs(b[i]) <= GYRO_BIAS_MAX_DPS, "gyro %s bias %.2f dps", name[i], b[i]);
        check(t, noise <= GYRO_NOISE_MAX_DPS, "gyro %s noise %.2f dps", name[i], noise);
    }
}

static void test_register_rw(imu_unit_t *u, test_ctx_t *t)
{
    uint8_t before = 0, after = 0;
    int32_t r0 = lsm6dsv16x_read_reg(&u->ctx, LSM6DSV16X_CTRL9, &before, 1);
    uint8_t probe = (uint8_t)(before ^ 0x02); /* toggle a benign config bit */
    int32_t r1 = lsm6dsv16x_write_reg(&u->ctx, LSM6DSV16X_CTRL9, &probe, 1);
    int32_t r2 = lsm6dsv16x_read_reg(&u->ctx, LSM6DSV16X_CTRL9, &after, 1);
    int32_t r3 = lsm6dsv16x_write_reg(&u->ctx, LSM6DSV16X_CTRL9, &before, 1);
    check(t, r0 == 0 && r1 == 0 && r2 == 0 && r3 == 0,
          "CTRL9 rw rc=%ld/%ld/%ld/%ld", (long)r0, (long)r1, (long)r2, (long)r3);
    check(t, after == probe, "CTRL9 readback 0x%02X (wrote 0x%02X)", after, probe);
}

/* -------------------------------------------------------------- per unit -- */

static void run_unit(int index)
{
    imu_unit_t *u = &s_units[index];
    test_ctx_t t = { 0 };
    unit_bind(u, index);

    ESP_LOGI(TAG, "--- unit %d (CS GPIO%d) ---", index, u->cs);

    if (!identity_probe(u)) {
        printf("UNIT_RESULT %d ABSENT 0/0 raw=0x%02X no_device\n", index,
               u->who_am_i);
        fflush(stdout);
        return;
    }
    u->present = true;
    test_ctx_t id = { 0 };
    check(&id, true, "ok");

    test_register_rw(u, &t);

    if (!unit_configure(u, &t, true)) {
        goto report;
    }
    vTaskDelay(pdMS_TO_TICKS(100));

    test_data_path(u, &t);
    test_static_window(u, &t);

report:;
    const char *detail = t.detail[0] ? t.detail : "ok";
    printf("UNIT_RESULT %d %s %d/%d raw=0x%02X %s\n", index,
           t.failed == 0 && t.passed > 0 ? "PASS" : "FAIL", t.passed,
           unit_total(&t), u->who_am_i, detail);
    fflush(stdout);
}

