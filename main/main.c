/* ------------------------------------------------------------------ main -- */

void app_main(void)
{
    vTaskDelay(pdMS_TO_TICKS(100));

#if CONFIG_RUN_MODE_DIAG
    run_diag();
    while (true) {
        vTaskDelay(pdMS_TO_TICKS(10000));
    }
#endif

    if (bus_init() != ESP_OK) {
        printf("BUS_INIT_FAILED\n");
        fflush(stdout);
        abort();
    }
    printf("BUS SPI=%dkHz units=%d mode=test\n", CONFIG_IMU_SPI_KHZ,
           CONFIG_UNIT_COUNT);
    fflush(stdout);

#if CONFIG_RUN_MODE_STREAM
    run_stream(); /* never returns */
#endif

    for (int i = 0; i < CONFIG_UNIT_COUNT; i++) {
        run_unit(i);
    }

    int present = 0;
    for (int i = 0; i < CONFIG_UNIT_COUNT; i++) {
        present += s_units[i].present ? 1 : 0;
    }
    printf("SUMMARY present=%d absent=%d count=%d\n", present,
           CONFIG_UNIT_COUNT - present, CONFIG_UNIT_COUNT);
    printf("MATRIX_DONE %d\n", CONFIG_UNIT_COUNT);
    fflush(stdout);

    while (true) {
        vTaskDelay(pdMS_TO_TICKS(10000));
    }
}
