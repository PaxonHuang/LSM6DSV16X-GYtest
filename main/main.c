/*
 * lsm6dsv16x_test — multi-source health test + streaming for LSM6DSV16X IMUs.
 *
 * Bus (ESP32-S3):
 *   GPIO12 -> SCLK, GPIO11 -> MOSI, GPIO13 <- MISO,
 *   one CS GPIO per source (default table: 1,2,4,5,6,7,8,9,10,14,15).
 *
 * Why one hardware CS0 routed through the GPIO matrix instead of one
 * spi_device per source: the S3 SPI peripheral only exposes three hardware CS
 * signals, so 6/11 sources cannot each own a hardware CS. A single SPI device
 * occupies CS0; before each transaction CS0 is routed to the target source's
 * pin and every other CS pin is returned to plain GPIO output (high). Manual
 * gpio_set_level() toggling was tried in an earlier project and read 0x00;
 * routing the hardware CS0 signal keeps the full CS waveform generated by the
 * peripheral. The release step (SIG_GPIO_OUT_IDX) matters: without it the
 * previous pin stays connected to CS0 and two devices are selected at once.
 *
 * The register access uses ST's official platform-independent driver
 * (components/lsm6dsv16x, lsm6dsv16x-pid v6.2.0). This file only supplies the
 * transport and the tests.
 *
 * Output contract (grepped by tools/run_tests.py; do not reword):
 *   UNIT_RESULT <index> <PASS|FAIL|ABSENT> <passed>/<total> raw=0x<xx> <detail>
 *   MATRIX_DONE <n>
 *   SUMMARY present=<n> absent=<n> count=<n>
 */

